package domain;

public abstract class Shape {
    private String id;
    private double x;
    private double y;

    public Shape(String id, double x, double y) {
        this.id = id;
        this.x = x;
        this.y = y;
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        if (id == null || id.trim().isEmpty()) {
            throw new IllegalArgumentException("The ID cannot be null or empty.");
        }
        this.id = id;
    }

    public double getX() {
        return x;
    }

    public void setX(double x) {
        this.x = x;
    }

    public double getY() {
        return y;
    }

    public void setY(double y) {
        this.y = y;
    }

    // Abstract methods to enforce polymorphism in subclasses
    public abstract double calculateArea();
    public abstract double calculatePerimeter();
}
